#!/usr/bin/env python3
"""Register offsets of the Adreno 8xx ("gen8") as a C header, from Linux's/Mesa's register database.

usage: tools/gen8-regs.py a6xx.xml a6xx_gmu.xml [more.xml ...] > OUT.h

The database (drivers/gpu/drm/msm/registers/adreno/*.xml) describes every generation at once: a
register may carry variants="A6XX", "A7XX-", "A6XX-A7XX", "A8XX" and so on, and the same name can
appear at several offsets for several generations. This keeps what is true of A8XX only and writes
    #define G8_<DOMAIN>_<NAME>        offset (in 32-bit words, as the database counts)
and for an array of registers
    #define G8_<DOMAIN>_<NAME>(i)     offset + i * stride
    #define G8_<DOMAIN>_<NAME>_<REG>(i) the register inside element i
Only offsets: no bitfields. The domain is left out of the name for the main one ("A6XX").
"""
import sys
import xml.etree.ElementTree as ET

CHIPS = ['A2XX', 'A3XX', 'A4XX', 'A5XX', 'A6XX', 'A7XX', 'A8XX']
WANT = CHIPS.index('A8XX')


def specificity(variants):
    """-1 if the variants leave A8XX out; else how closely they aim at it (the higher, the closer)."""
    if not variants:
        return 0
    best = -1
    for part in variants.replace(',', ' ').split():
        if '-' in part:
            lo, hi = part.split('-', 1)
            lo = CHIPS.index(lo) if lo else 0
            hi = CHIPS.index(hi) if hi else len(CHIPS) - 1
            if lo <= WANT <= hi:
                best = max(best, 1 + lo)
        elif part in CHIPS and CHIPS.index(part) == WANT:
            best = max(best, 100)
    return best


def applies(variants):
    return specificity(variants) >= 0


def strip(tag):
    return tag.split('}', 1)[-1]


def main():
    seen = {}
    out = ['/* generated by tools/gen8-regs.py from ' + ' '.join(a.rsplit('/', 1)[-1] for a in sys.argv[1:]) + ' */',
           '#pragma once']
    for path in sys.argv[1:]:
        root = ET.parse(path).getroot()
        for domain in root.iter():
            if strip(domain.tag) != 'domain':
                continue
            dname = domain.get('name')
            prefix = 'G8_' if dname == 'A6XX' else 'G8_' + dname.replace('A6XX_', '').replace('A7XX_', '') + '_'
            if not applies(domain.get('variants')):
                continue
            for node in domain:
                tag = strip(node.tag)
                if not applies(node.get('variants')):
                    continue
                name = node.get('name')
                if tag in ('reg32', 'reg64') and name and node.get('offset'):
                    key = prefix + name
                    spec = specificity(node.get('variants'))
                    if key in seen and seen[key][0] >= spec:
                        continue
                    line = '#define %-56s 0x%05x' % (key, int(node.get('offset'), 0))
                    if key in seen:
                        out[seen[key][1]] = line
                    else:
                        out.append(line)
                    seen[key] = (spec, len(out) - 1 if key not in seen else seen[key][1])
                elif tag == 'array' and name and node.get('offset'):
                    key = prefix + name
                    if key in seen:
                        continue
                    seen[key] = (specificity(node.get('variants')), len(out))
                    off, stride = int(node.get('offset'), 0), int(node.get('stride', '1'), 0)
                    out.append('#define %-56s (0x%05x + (i) * 0x%x)' % (key + '(i)', off, stride))
                    out.append('#define %-56s %s' % (key + '_LEN', node.get('length', '0')))
                    for sub in node:
                        if strip(sub.tag) in ('reg32', 'reg64') and applies(sub.get('variants')) and sub.get('name'):
                            out.append('#define %-56s (0x%05x + (i) * 0x%x + 0x%x)' % (
                                key + '_' + sub.get('name') + '(i)', off, stride, int(sub.get('offset', '0'), 0)))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
